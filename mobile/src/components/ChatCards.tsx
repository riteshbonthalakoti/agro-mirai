import React from 'react';
import { Text, View } from 'react-native';
import { ChatCard } from '../api';
import { Icon } from '../../icons';
import { C, S, levelColor } from '../theme';

function CardShell({ icon, accent, title, field, children }: {
  icon: 'drop' | 'bug' | 'sprout'; accent: string; title: string; field: string; children: React.ReactNode;
}) {
  return (
    <View style={{ flexDirection: 'row', backgroundColor: '#fff', borderRadius: 16, marginTop: S.sm, borderWidth: 1, borderColor: C.border, overflow: 'hidden' }}>
      <View style={{ width: 4, backgroundColor: accent }} />
      <View style={{ flex: 1, padding: S.sm }}>
        <View style={{ flexDirection: 'row', alignItems: 'center', marginBottom: 4 }}>
          <Icon name={icon} size={14} color={accent} />
          <Text style={{ fontSize: 12, fontWeight: '800', color: C.text, marginLeft: 6, flex: 1 }} numberOfLines={1}>{title}</Text>
        </View>
        <Text style={{ fontSize: 11, color: C.muted, marginBottom: 6 }} numberOfLines={1}>{field}</Text>
        {children}
      </View>
    </View>
  );
}

/** Real, already-computed crop/irrigation/disease cards the chat route
 * attaches to a reply (Module 58) -- never generated by the LLM itself,
 * so these always carry the same numbers the rest of the app shows. */
export function ChatCardView({ card }: { card: ChatCard }) {
  if (card.type === 'irrigation') {
    return (
      <CardShell icon="drop" accent={levelColor(card.urgency)} title="Irrigation" field={card.field}>
        <Text style={{ fontSize: 20, fontWeight: '800', color: C.text }}>{Math.round(card.depth_mm)}mm</Text>
        <Text style={{ fontSize: 11, color: C.muted, marginTop: 2 }}>
          {new Date(card.window_start_at).toLocaleDateString(undefined, { day: 'numeric', month: 'short' })} · {card.urgency}
        </Text>
      </CardShell>
    );
  }
  if (card.type === 'disease') {
    return (
      <CardShell icon="bug" accent={levelColor(card.risk_level)} title={card.disease} field={card.field}>
        <Text style={{ fontSize: 14, fontWeight: '800', color: levelColor(card.risk_level), textTransform: 'uppercase' }}>{card.risk_level} risk</Text>
        {card.recommended_action ? <Text style={{ fontSize: 12, color: C.text, marginTop: 4 }} numberOfLines={2}>{card.recommended_action}</Text> : null}
      </CardShell>
    );
  }
  return (
    <CardShell icon="sprout" accent={C.accent} title={card.crop} field={card.field}>
      <Text style={{ fontSize: 14, fontWeight: '800', color: C.accent }}>{Math.round(card.confidence * 100)}% confidence</Text>
      {card.rationale ? <Text style={{ fontSize: 12, color: C.text, marginTop: 4 }} numberOfLines={2}>{card.rationale}</Text> : null}
    </CardShell>
  );
}
