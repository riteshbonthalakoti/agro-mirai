// Gradle's own launcher JVM was resolving to a mismatched JDK (25,
// JetBrains Runtime from PATH) while the daemon used Android Studio's
// bundled JBR (17) -- that mismatch is the root cause behind release
// builds failing at :app:configureCMakeRelWithDebInfo with "WARNING: A
// restricted method in java.lang.System has been called", which AGP's
// prefab/CMake glue treats as a fatal build error (any stderr line from
// that step is fatal -- same failure class as the earlier
// JDK_JAVA_OPTIONS issue in Module 53's handoff notes, different
// trigger). Pinning org.gradle.java.home to a known stock JDK 17 fixes
// it. android/ is gitignored and regenerated by every `expo prebuild`,
// so this has to be reapplied at prebuild time, not hand-edited once.
//
// If this JDK path doesn't exist on a machine (Eclipse Adoptium 17 isn't
// installed there), this plugin is a no-op -- gradle.properties keeps
// whatever default it already resolves to, so prebuild never fails
// because of this plugin itself.
const fs = require('fs');
const { withGradleProperties } = require('expo/config-plugins');

const JDK17_PATH = 'C:\\\\Program Files\\\\Eclipse Adoptium\\\\jdk-17.0.20.101-hotspot';
const JDK17_PROBE = 'C:\\Program Files\\Eclipse Adoptium\\jdk-17.0.20.101-hotspot';

module.exports = function withPinnedJdk(config) {
  if (!fs.existsSync(JDK17_PROBE)) return config;
  return withGradleProperties(config, (cfg) => {
    cfg.modResults.push({
      type: 'property',
      key: 'org.gradle.java.home',
      value: JDK17_PATH,
    });
    return cfg;
  });
};
